-- ==========================================
-- MICROSOFT 365 COMPANY EMAIL (PLATFORM DB) -- additive only
--
-- Applied by server/_migrate_add_microsoft_email.js (which reads THIS file, so the two can never drift) and
-- included verbatim in platformSchema.postgresql.sql for a fresh bootstrap. Everything is CREATE ... IF NOT
-- EXISTS / ADD COLUMN IF NOT EXISTS / guarded constraints: re-running changes nothing, and no existing row,
-- table or column is dropped, renamed or rewritten.
--
-- SECRETS: no password of any kind is stored. The OAuth tokens are stored ONLY as AES-256-GCM ciphertext
-- (server/utils/secretBox.js), bound to their row. The audit log never stores message content or tokens.
-- ==========================================

-- Where a domain's mail is hosted. 'external' = the customer's own provider (Microsoft 365): ZioVenture never asks
-- for, or generates, MX / SPF / DKIM / DMARC changes for it.
ALTER TABLE "email_domains" ADD COLUMN IF NOT EXISTS "mail_hosting" varchar(30) NOT NULL DEFAULT 'external';

-- Which provider a mailbox record is linked to. A mailbox record on its own creates NOTHING at Microsoft.
ALTER TABLE "mailboxes" ADD COLUMN IF NOT EXISTS "provider" varchar(30) NOT NULL DEFAULT 'none';
ALTER TABLE "mailboxes" ADD COLUMN IF NOT EXISTS "link_state" varchar(20) NOT NULL DEFAULT 'unlinked';
ALTER TABLE "mailboxes" ADD COLUMN IF NOT EXISTS "linked_at" timestamp DEFAULT NULL;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'chk_mailboxes_link_state') THEN
    ALTER TABLE "mailboxes" ADD CONSTRAINT "chk_mailboxes_link_state" CHECK ("link_state" IN ('unlinked', 'awaiting_user', 'linked'));
  END IF;
END $$;

-- ---------- one Microsoft 365 organisation per ZioVenture company ----------
CREATE TABLE IF NOT EXISTS "email_ms_company_connections" (
  "id" integer GENERATED BY DEFAULT AS IDENTITY,
  "company_id" integer NOT NULL,
  "ms_tenant_id" varchar(64) DEFAULT NULL,
  "tenant_source" varchar(30) NOT NULL DEFAULT 'domain_discovery',
  "domain_id" integer DEFAULT NULL,
  "status" varchar(20) NOT NULL DEFAULT 'pending' CHECK ("status" IN ('pending', 'ready', 'error', 'disabled')),
  "last_checked_at" timestamp DEFAULT NULL,
  "last_error" varchar(300) DEFAULT NULL,
  "created_by" integer DEFAULT NULL,
  "created_at" timestamp DEFAULT CURRENT_TIMESTAMP,
  "updated_at" timestamp DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY ("id"),
  CONSTRAINT "uq_msconn_company" UNIQUE ("company_id")
);

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_msconn_company_id') THEN
    ALTER TABLE "email_ms_company_connections" ADD CONSTRAINT "fk_msconn_company_id" FOREIGN KEY ("company_id") REFERENCES "companies" ("id") ON DELETE CASCADE;
  END IF;
END $$;

-- ---------- single-use OAuth state (CSRF + PKCE) ----------
CREATE TABLE IF NOT EXISTS "email_ms_oauth_states" (
  "id" integer GENERATED BY DEFAULT AS IDENTITY,
  "state_hash" varchar(64) NOT NULL,
  "company_id" integer NOT NULL,
  "tenant_user_id" integer NOT NULL,
  "mailbox_id" integer NOT NULL,
  "nonce_hash" varchar(64) NOT NULL,
  "code_verifier_enc" text NOT NULL,
  "return_portal" varchar(10) NOT NULL DEFAULT 'employee',
  "expires_at" timestamp NOT NULL,
  "consumed_at" timestamp DEFAULT NULL,
  "created_at" timestamp DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY ("id"),
  CONSTRAINT "uq_msstate_hash" UNIQUE ("state_hash")
);

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_msstate_company_id') THEN
    ALTER TABLE "email_ms_oauth_states" ADD CONSTRAINT "fk_msstate_company_id" FOREIGN KEY ("company_id") REFERENCES "companies" ("id") ON DELETE CASCADE;
  END IF;
END $$;

CREATE INDEX IF NOT EXISTS "idx_msstate_expires" ON "email_ms_oauth_states" ("expires_at");

-- ---------- one connected Microsoft account per employee mailbox ----------
CREATE TABLE IF NOT EXISTS "email_ms_user_connections" (
  "id" integer GENERATED BY DEFAULT AS IDENTITY,
  "company_id" integer NOT NULL,
  "tenant_user_id" integer NOT NULL,
  "mailbox_id" integer NOT NULL,
  "ms_tenant_id" varchar(64) NOT NULL,
  "ms_user_oid" varchar(64) NOT NULL,
  "ms_account" varchar(255) NOT NULL,
  "status" varchar(20) NOT NULL DEFAULT 'connected' CHECK ("status" IN ('connected', 'reauth_required', 'disabled')),
  "scopes" text DEFAULT NULL,
  "access_token_enc" text DEFAULT NULL,
  "refresh_token_enc" text DEFAULT NULL,
  "access_expires_at" timestamp DEFAULT NULL,
  "last_refreshed_at" timestamp DEFAULT NULL,
  "last_error" varchar(300) DEFAULT NULL,
  "connected_at" timestamp DEFAULT CURRENT_TIMESTAMP,
  "created_at" timestamp DEFAULT CURRENT_TIMESTAMP,
  "updated_at" timestamp DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY ("id"),
  CONSTRAINT "uq_msuser_company_user" UNIQUE ("company_id", "tenant_user_id"),
  CONSTRAINT "uq_msuser_mailbox" UNIQUE ("mailbox_id")
);

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_msuser_company_id') THEN
    ALTER TABLE "email_ms_user_connections" ADD CONSTRAINT "fk_msuser_company_id" FOREIGN KEY ("company_id") REFERENCES "companies" ("id") ON DELETE CASCADE;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_msuser_mailbox_id') THEN
    ALTER TABLE "email_ms_user_connections" ADD CONSTRAINT "fk_msuser_mailbox_id" FOREIGN KEY ("mailbox_id") REFERENCES "mailboxes" ("id") ON DELETE CASCADE;
  END IF;
END $$;

