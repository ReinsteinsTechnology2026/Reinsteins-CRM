-- ---------- audit log: who did what to which connection / mailbox. Never message content, never tokens. ----------
CREATE TABLE IF NOT EXISTS "email_audit_log" (
  "id" bigint GENERATED BY DEFAULT AS IDENTITY,
  "company_id" integer NOT NULL,
  "actor_user_id" integer DEFAULT NULL,
  "action" varchar(60) NOT NULL,
  "target_type" varchar(30) DEFAULT NULL,
  "target_id" varchar(64) DEFAULT NULL,
  "detail" text DEFAULT NULL,
  "created_at" timestamp DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY ("id")
);

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_emailaudit_company_id') THEN
    ALTER TABLE "email_audit_log" ADD CONSTRAINT "fk_emailaudit_company_id" FOREIGN KEY ("company_id") REFERENCES "companies" ("id") ON DELETE CASCADE;
  END IF;
END $$;

CREATE INDEX IF NOT EXISTS "idx_emailaudit_company_created" ON "email_audit_log" ("company_id", "created_at");
