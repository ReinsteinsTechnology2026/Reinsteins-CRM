// ==========================================
// ZIOVAULT -- TABLE, FUNCTION AND TRIGGER DEFINITIONS (single source of truth)
//
// The migration (server/_migrate_add_ziovault.js, existing tenants and the legacy database) runs these statements in their
// re-runnable form. The very same text is appended to server/schemas/tenantSchema.postgresql.sql so every NEWLY provisioned
// tenant gets them; _test_ziovault_schema.js fails if the two ever drift apart.
//
// EVERY sensitive column holds CIPHERTEXT or WRAPPED KEY MATERIAL produced in the browser (see server/ZIOVAULT_ARCHITECTURE.md).
// There is no plaintext secret, no JSONB with secrets and no searchable text derived from a secret anywhere in these tables.
// No company_id column: tenant isolation is the tenant's own database.
//
// Data deletion policy: foreign keys to users are RESTRICT for anything that owns personal data and CASCADE only for rows that
// are pure access grants; nothing here deletes a person's vault or a company credential automatically.
//
// Tables
//   zv_accounts               one per user: KDF parameters + the encrypted vault-key / private-key / recovery envelopes + PUBLIC key
//   zv_account_history        append-only copies of every replaced vault-key envelope (a hijacked session cannot silently destroy a vault)
//   zv_folders                per-user folders (encrypted names)
//   zv_collections            company collections (encrypted names); `rotation_required` after a member left
//   zv_collection_members     membership: rights + the collection keys wrapped to that member
//   zv_items                  personal (owner_user_id) XOR company (collection_id) items: encrypted details + encrypted secret
//   zv_item_keys              wrapped item keys: for the owner, for a shared recipient, or under a collection key
//   zv_grants                 item shares: rights, expiry, delegation chain (parent_grant_id), revocation history
//   zv_attachments            encrypted attachments (metadata + ciphertext as bytea, size limited)
//   zv_audit_events           append-only audit trail (fixed vocabulary, never any secret, title or free text)
// Functions/triggers
//   zv_audit_immutable        refuses UPDATE / DELETE / TRUNCATE on zv_audit_events
//   zv_offboard_user          runs inside the SAME transaction as the users update that deactivates someone
// ==========================================

