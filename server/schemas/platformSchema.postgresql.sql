-- ---------- Phase 13: email_delivery_logs -- durable, honest email
-- delivery history. Stores template_data (small JSON of the values a
-- template needs), never the rendered HTML body -- enough to
-- regenerate the exact same email for a retry. company_id is ON
-- DELETE SET NULL: a delivery record survives its company's
-- deletion. ----------
CREATE TABLE IF NOT EXISTS "email_delivery_logs" (
  "id" integer GENERATED BY DEFAULT AS IDENTITY,
  "company_id" integer DEFAULT NULL,
  "recipient_email" varchar(255) DEFAULT NULL,
  "recipient_name" varchar(255) DEFAULT NULL,
  "email_type" varchar(50) NOT NULL,
  "subject" varchar(255) NOT NULL,
  "template_data" jsonb DEFAULT NULL,
  "status" varchar NOT NULL DEFAULT 'pending' CHECK ("status" IN ('pending', 'sent', 'failed', 'skipped')),
  "provider_message_id" varchar(255) DEFAULT NULL,
  "error_message" varchar(500) DEFAULT NULL,
  "retry_count" integer NOT NULL DEFAULT 0,
  "last_attempt_at" timestamp DEFAULT NULL,
  "sent_at" timestamp DEFAULT NULL,
  "created_at" timestamp DEFAULT CURRENT_TIMESTAMP,
  "updated_at" timestamp DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY ("id")
);

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_emaillog_company_id') THEN
    ALTER TABLE "email_delivery_logs" ADD CONSTRAINT "fk_emaillog_company_id" FOREIGN KEY ("company_id") REFERENCES "companies" ("id") ON DELETE SET NULL;
  END IF;
END $$;

CREATE INDEX IF NOT EXISTS "idx_emaillog_company_id" ON "email_delivery_logs" ("company_id");
CREATE INDEX IF NOT EXISTS "idx_emaillog_status" ON "email_delivery_logs" ("status");
CREATE INDEX IF NOT EXISTS "idx_emaillog_email_type" ON "email_delivery_logs" ("email_type");
