-- ---------- Phase 10/11: payments -- no card/CVV/bank data, only
-- provider-issued reference IDs. company_id/plan_id use ON DELETE
-- RESTRICT: a company or plan with real payment history can never be
-- deleted out from under its financial records. ----------
CREATE TABLE IF NOT EXISTS "payments" (
  "id" integer GENERATED BY DEFAULT AS IDENTITY,
  "company_id" integer NOT NULL,
  "plan_id" integer NOT NULL,
  "amount" numeric(10,2) NOT NULL,
  "currency" varchar(3) NOT NULL DEFAULT 'INR',
  "billing_cycle" varchar NOT NULL CHECK ("billing_cycle" IN ('monthly', 'yearly', 'one_time')),
  "payment_status" varchar NOT NULL DEFAULT 'pending' CHECK ("payment_status" IN ('pending', 'paid', 'failed', 'refunded', 'cancelled')),
  "payment_provider" varchar(50) DEFAULT NULL,
  "provider_payment_id" varchar(255) DEFAULT NULL,
  "provider_order_id" varchar(255) DEFAULT NULL,
  "invoice_number" varchar(50) DEFAULT NULL,
  "notes" varchar(500) DEFAULT NULL,
  "paid_at" timestamp DEFAULT NULL,
  "created_at" timestamp DEFAULT CURRENT_TIMESTAMP,
  "updated_at" timestamp DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY ("id"),
  CONSTRAINT "uq_payments_provider_payment_id" UNIQUE ("provider_payment_id"),
  CONSTRAINT "uq_payments_invoice_number" UNIQUE ("invoice_number")
);

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_payments_company_id') THEN
    ALTER TABLE "payments" ADD CONSTRAINT "fk_payments_company_id" FOREIGN KEY ("company_id") REFERENCES "companies" ("id") ON DELETE RESTRICT;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_payments_plan_id') THEN
    ALTER TABLE "payments" ADD CONSTRAINT "fk_payments_plan_id" FOREIGN KEY ("plan_id") REFERENCES "subscription_plans" ("id") ON DELETE RESTRICT;
  END IF;
END $$;

CREATE INDEX IF NOT EXISTS "idx_payments_company_id" ON "payments" ("company_id");
CREATE INDEX IF NOT EXISTS "idx_payments_status" ON "payments" ("payment_status");
CREATE INDEX IF NOT EXISTS "idx_payments_paid_at" ON "payments" ("paid_at");

-- ---------- Phase 12: subscription_history -- append-only lifecycle
-- event log AND the durable dedupe store for reminder emails. ON
-- DELETE CASCADE (unlike payments' RESTRICT): operational history has
-- no financial/legal retention requirement the way payment records
-- do. ----------
CREATE TABLE IF NOT EXISTS "subscription_history" (
  "id" integer GENERATED BY DEFAULT AS IDENTITY,
  "company_id" integer NOT NULL,
  "plan_id" integer DEFAULT NULL,
  "event_type" varchar(50) NOT NULL,
  "previous_status" varchar(20) DEFAULT NULL,
  "new_status" varchar(20) DEFAULT NULL,
  "previous_plan_id" integer DEFAULT NULL,
  "new_plan_id" integer DEFAULT NULL,
  "effective_at" timestamp DEFAULT NULL,
  "source" varchar(20) NOT NULL DEFAULT 'system',
  "reference_payment_id" integer DEFAULT NULL,
  "notes" varchar(500) DEFAULT NULL,
  "created_at" timestamp DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY ("id")
);

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_subhist_company_id') THEN
    ALTER TABLE "subscription_history" ADD CONSTRAINT "fk_subhist_company_id" FOREIGN KEY ("company_id") REFERENCES "companies" ("id") ON DELETE CASCADE;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_subhist_payment_id') THEN
    ALTER TABLE "subscription_history" ADD CONSTRAINT "fk_subhist_payment_id" FOREIGN KEY ("reference_payment_id") REFERENCES "payments" ("id") ON DELETE SET NULL;
  END IF;
END $$;

CREATE INDEX IF NOT EXISTS "idx_subhist_company_id" ON "subscription_history" ("company_id");
CREATE INDEX IF NOT EXISTS "idx_subhist_event_type" ON "subscription_history" ("event_type");
CREATE INDEX IF NOT EXISTS "idx_subhist_dedupe" ON "subscription_history" ("company_id", "event_type", "effective_at");

