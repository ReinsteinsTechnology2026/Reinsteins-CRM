// ==========================================
// SMART SHEETS -- TABLE DEFINITIONS (single source of truth)
//
// The migration (server/_migrate_add_smart_sheets.js, existing tenants and the legacy database) runs
// these statements in their re-runnable form. The very same text is appended, verbatim, to
// server/schemas/tenantSchema.postgresql.sql so every NEWLY provisioned tenant gets the tables;
// _test_smart_sheets_migration.js fails if the two ever drift apart.
//
// The migration form of every statement is idempotent (IF NOT EXISTS), additive only, and foreign keys are declared
// inside CREATE TABLE so a half-finished run can never leave a table without its constraints.
// No company_id column: tenant isolation is the tenant's own database (same as shift_schedules).
//
// Data model (cell-level, not one big blob):
//   smart_sheets            one row per spreadsheet; `revision` is bumped inside every write
//                           transaction and doubles as the per-sheet write lock, which is what
//                           makes concurrent edits apply in one well-defined order (see
//                           services/smartSheetStore.js).
//   smart_sheet_access      explicit employee assignments (view | edit). Admins are never listed
//                           here: admin-tier access comes from role/system_access.
//   smart_sheet_worksheets  the tabs. ws_key is the editor's worksheet id (client-generated for
//                           new tabs, validated server-side).
//   smart_sheet_cells       one row per non-empty cell; `cell` is the editor's cell JSON
//                           (value, formula, inline style).
// ==========================================

const SMART_SHEETS_SCHEMA_STATEMENTS = [
`CREATE TABLE "smart_sheets" (
  "id" integer GENERATED BY DEFAULT AS IDENTITY,
  "name" varchar(150) NOT NULL,
  "status" varchar NOT NULL DEFAULT 'active' CHECK ("status" IN ('active', 'archived')),
  "revision" bigint NOT NULL DEFAULT 0,
  "source_file_name" varchar(255) DEFAULT NULL,
  "source_file_path" varchar(500) DEFAULT NULL,
  "created_by" integer DEFAULT NULL,
  "updated_by" integer DEFAULT NULL,
  "created_at" timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "updated_at" timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "deleted_at" timestamp NULL DEFAULT NULL,
  PRIMARY KEY ("id"),
  CONSTRAINT "fk_smart_sheets_created_by" FOREIGN KEY ("created_by") REFERENCES "users" ("id") ON DELETE SET NULL,
  CONSTRAINT "fk_smart_sheets_updated_by" FOREIGN KEY ("updated_by") REFERENCES "users" ("id") ON DELETE SET NULL
)`,
`CREATE TABLE "smart_sheet_access" (
  "id" integer GENERATED BY DEFAULT AS IDENTITY,
  "sheet_id" integer NOT NULL,
  "user_id" integer NOT NULL,
  "permission" varchar NOT NULL DEFAULT 'edit' CHECK ("permission" IN ('view', 'edit')),
  "granted_by" integer DEFAULT NULL,
  "granted_at" timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY ("id"),
  CONSTRAINT "uq_smart_sheet_access_sheet_user" UNIQUE ("sheet_id", "user_id"),
  CONSTRAINT "fk_smart_sheet_access_sheet" FOREIGN KEY ("sheet_id") REFERENCES "smart_sheets" ("id") ON DELETE CASCADE,
  CONSTRAINT "fk_smart_sheet_access_user" FOREIGN KEY ("user_id") REFERENCES "users" ("id") ON DELETE CASCADE,
  CONSTRAINT "fk_smart_sheet_access_granted_by" FOREIGN KEY ("granted_by") REFERENCES "users" ("id") ON DELETE SET NULL
)`,
`CREATE TABLE "smart_sheet_worksheets" (
  "id" integer GENERATED BY DEFAULT AS IDENTITY,
  "sheet_id" integer NOT NULL,
  "ws_key" varchar(36) NOT NULL,
  "name" varchar(31) NOT NULL,
  "position" integer NOT NULL DEFAULT 0,
  "row_count" integer NOT NULL DEFAULT 1000,
  "column_count" integer NOT NULL DEFAULT 26,
  "layout" jsonb NOT NULL DEFAULT '{}'::jsonb,
  PRIMARY KEY ("id"),
  CONSTRAINT "uq_smart_sheet_worksheets_key" UNIQUE ("sheet_id", "ws_key"),
  CONSTRAINT "fk_smart_sheet_worksheets_sheet" FOREIGN KEY ("sheet_id") REFERENCES "smart_sheets" ("id") ON DELETE CASCADE
)`,
`CREATE TABLE "smart_sheet_cells" (
  "worksheet_id" integer NOT NULL,
  "row_idx" integer NOT NULL,
  "col_idx" integer NOT NULL,
  "sheet_id" integer NOT NULL,
  "cell" jsonb NOT NULL,
  "revision" bigint NOT NULL DEFAULT 0,
  "updated_by" integer DEFAULT NULL,
  "updated_at" timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY ("worksheet_id", "row_idx", "col_idx"),
  CONSTRAINT "fk_smart_sheet_cells_worksheet" FOREIGN KEY ("worksheet_id") REFERENCES "smart_sheet_worksheets" ("id") ON DELETE CASCADE,
  CONSTRAINT "fk_smart_sheet_cells_sheet" FOREIGN KEY ("sheet_id") REFERENCES "smart_sheets" ("id") ON DELETE CASCADE,
  CONSTRAINT "fk_smart_sheet_cells_updated_by" FOREIGN KEY ("updated_by") REFERENCES "users" ("id") ON DELETE SET NULL
)`,
`CREATE INDEX "idx_smart_sheets_status_deleted" ON "smart_sheets" ("status", "deleted_at")`,
`CREATE INDEX "idx_smart_sheet_access_user" ON "smart_sheet_access" ("user_id")`,
`CREATE INDEX "idx_smart_sheet_worksheets_sheet_position" ON "smart_sheet_worksheets" ("sheet_id", "position")`,
`CREATE INDEX "idx_smart_sheet_cells_sheet" ON "smart_sheet_cells" ("sheet_id")`,
];

const SMART_SHEETS_TABLES = ["smart_sheets", "smart_sheet_access", "smart_sheet_worksheets", "smart_sheet_cells"];

// The migration form: identical text, made re-runnable. (The schema file deliberately keeps the
// plain form -- it only ever runs against an empty database, and tenantProvisioningService
// extracts table names with /CREATE TABLE\s+"?(\w+)"?/, which would read "IF" as a table name.)
const SMART_SHEETS_MIGRATION_STATEMENTS = SMART_SHEETS_SCHEMA_STATEMENTS.map((statement) =>
  statement
    .replace(/^CREATE TABLE "/, "CREATE TABLE IF NOT EXISTS \"")
    .replace(/^CREATE INDEX "/, "CREATE INDEX IF NOT EXISTS \"")
);

module.exports = { SMART_SHEETS_SCHEMA_STATEMENTS, SMART_SHEETS_MIGRATION_STATEMENTS, SMART_SHEETS_TABLES };
