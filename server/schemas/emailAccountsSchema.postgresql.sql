-- ==========================================
-- EMAIL ACCOUNTS (PLATFORM DB) -- additive only
--
-- A unified email client: every employee connects their OWN existing accounts (Gmail, Google Workspace, Outlook.com / Hotmail,
-- Microsoft 365 work or school). ZioVenture hosts no mailbox, sells no licence and needs no verified company domain.
--
-- Applied by server/_migrate_add_email_accounts.js (which reads THIS file) and included verbatim in
-- platformSchema.postgresql.sql. Every statement is CREATE ... IF NOT EXISTS / guarded, so re-running changes nothing, and no
-- existing table, column or row (including the earlier company-managed mailbox tables) is altered or dropped.
--
-- SECRETS: no password of any kind. OAuth tokens are stored only as AES-256-GCM ciphertext (server/utils/secretBox.js) bound to
-- (company, employee, provider, provider account). No message content is stored here -- mail stays at the provider.
-- ==========================================

CREATE TABLE IF NOT EXISTS "email_accounts" (
  "id" integer GENERATED BY DEFAULT AS IDENTITY,
  "company_id" integer NOT NULL,
  "tenant_user_id" integer NOT NULL,
  "provider" varchar(20) NOT NULL CHECK ("provider" IN ('google', 'microsoft')),
  "account_kind" varchar(30) NOT NULL CHECK ("account_kind" IN ('gmail', 'google_workspace', 'outlook_personal', 'microsoft_365')),
  "email_address" varchar(255) NOT NULL,
  "display_name" varchar(255) DEFAULT NULL,
  "provider_account_id" varchar(128) NOT NULL,
  "provider_tenant_id" varchar(64) DEFAULT NULL,
  "status" varchar(20) NOT NULL DEFAULT 'connected' CHECK ("status" IN ('connected', 'reauth_required', 'disabled')),
  "scopes" text DEFAULT NULL,
  "access_token_enc" text DEFAULT NULL,
  "refresh_token_enc" text DEFAULT NULL,
  "access_expires_at" timestamp DEFAULT NULL,
  "last_refreshed_at" timestamp DEFAULT NULL,
  "last_error" varchar(300) DEFAULT NULL,
  "sync_cursor" text DEFAULT NULL,
  "last_sync_at" timestamp DEFAULT NULL,
  "next_sync_at" timestamp DEFAULT NULL,
  "sync_failures" integer NOT NULL DEFAULT 0,
  "sync_error" varchar(300) DEFAULT NULL,
  "unread_inbox" integer NOT NULL DEFAULT 0,
  "unread_checked_at" timestamp DEFAULT NULL,
  "color" varchar(9) DEFAULT NULL,
  "connected_at" timestamp DEFAULT CURRENT_TIMESTAMP,
  "created_at" timestamp DEFAULT CURRENT_TIMESTAMP,
  "updated_at" timestamp DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY ("id"),
  CONSTRAINT "uq_emailaccounts_identity" UNIQUE ("company_id", "tenant_user_id", "provider", "provider_account_id")
);

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_emailaccounts_company_id') THEN
    ALTER TABLE "email_accounts" ADD CONSTRAINT "fk_emailaccounts_company_id" FOREIGN KEY ("company_id") REFERENCES "companies" ("id") ON DELETE CASCADE;
  END IF;
END $$;

CREATE INDEX IF NOT EXISTS "idx_emailaccounts_user" ON "email_accounts" ("company_id", "tenant_user_id");
CREATE INDEX IF NOT EXISTS "idx_emailaccounts_sync" ON "email_accounts" ("status", "next_sync_at");
CREATE INDEX IF NOT EXISTS "idx_emailaccounts_provider_email" ON "email_accounts" ("provider", "email_address");

-- ---------- single-use OAuth state (CSRF + PKCE), for every provider ----------
CREATE TABLE IF NOT EXISTS "email_account_oauth_states" (
  "id" integer GENERATED BY DEFAULT AS IDENTITY,
  "state_hash" varchar(64) NOT NULL,
  "company_id" integer NOT NULL,
  "tenant_user_id" integer NOT NULL,
  "provider" varchar(20) NOT NULL,
  "account_id" integer DEFAULT NULL,
  "nonce_hash" varchar(64) NOT NULL,
  "code_verifier_enc" text NOT NULL,
  "return_portal" varchar(10) NOT NULL DEFAULT 'employee',
  "expires_at" timestamp NOT NULL,
  "consumed_at" timestamp DEFAULT NULL,
  "created_at" timestamp DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY ("id"),
  CONSTRAINT "uq_emailacctstate_hash" UNIQUE ("state_hash")
);

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_emailacctstate_company_id') THEN
    ALTER TABLE "email_account_oauth_states" ADD CONSTRAINT "fk_emailacctstate_company_id" FOREIGN KEY ("company_id") REFERENCES "companies" ("id") ON DELETE CASCADE;
  END IF;
END $$;

CREATE INDEX IF NOT EXISTS "idx_emailacctstate_expires" ON "email_account_oauth_states" ("expires_at");

-- ---------- provider push subscriptions (Gmail watch, Microsoft Graph change notifications) ----------
CREATE TABLE IF NOT EXISTS "email_push_subscriptions" (
  "id" integer GENERATED BY DEFAULT AS IDENTITY,
  "account_id" integer NOT NULL,
  "provider" varchar(20) NOT NULL,
  "subscription_id" varchar(255) DEFAULT NULL,
  "client_state_hash" varchar(64) DEFAULT NULL,
  "resource" varchar(255) DEFAULT NULL,
  "expires_at" timestamp DEFAULT NULL,
  "status" varchar(20) NOT NULL DEFAULT 'active',
  "last_notification_at" timestamp DEFAULT NULL,
  "last_error" varchar(300) DEFAULT NULL,
  "created_at" timestamp DEFAULT CURRENT_TIMESTAMP,
  "updated_at" timestamp DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY ("id"),
  CONSTRAINT "uq_emailpush_account" UNIQUE ("account_id")
);

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_emailpush_account_id') THEN
    ALTER TABLE "email_push_subscriptions" ADD CONSTRAINT "fk_emailpush_account_id" FOREIGN KEY ("account_id") REFERENCES "email_accounts" ("id") ON DELETE CASCADE;
  END IF;
END $$;

CREATE INDEX IF NOT EXISTS "idx_emailpush_subscription" ON "email_push_subscriptions" ("subscription_id");
CREATE INDEX IF NOT EXISTS "idx_emailpush_expires" ON "email_push_subscriptions" ("expires_at");

-- ---------- new-mail events: the duplicate guard (one row per message per account, ever) ----------
CREATE TABLE IF NOT EXISTS "email_new_mail_events" (
  "id" bigint GENERATED BY DEFAULT AS IDENTITY,
  "account_id" integer NOT NULL,
  "provider_message_id" varchar(255) NOT NULL,
  "created_at" timestamp DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY ("id"),
  CONSTRAINT "uq_emailevents_message" UNIQUE ("account_id", "provider_message_id")
);

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_emailevents_account_id') THEN
    ALTER TABLE "email_new_mail_events" ADD CONSTRAINT "fk_emailevents_account_id" FOREIGN KEY ("account_id") REFERENCES "email_accounts" ("id") ON DELETE CASCADE;
  END IF;
END $$;

CREATE INDEX IF NOT EXISTS "idx_emailevents_created" ON "email_new_mail_events" ("created_at");
