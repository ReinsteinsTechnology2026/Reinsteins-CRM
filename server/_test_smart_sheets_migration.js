// Smart Sheets -- database schema and migration. CI has no database for these tests, so this
// checks the SQL statically and runs the migration script's logic against a recording fake pool.
// (The statements themselves were reviewed against PostgreSQL syntax; see the PR notes for the
// manual run against a disposable PostgreSQL.) Run: node --test _test_smart_sheets_migration.js

const test = require("node:test");
const assert = require("node:assert/strict");
const fs = require("fs");
const path = require("path");

const {
    SMART_SHEETS_SCHEMA_STATEMENTS,
    SMART_SHEETS_MIGRATION_STATEMENTS,
    SMART_SHEETS_TABLES,
} = require("./schemas/smartSheetsDdl");
const migration = require("./_migrate_add_smart_sheets");

const schemaFile = fs.readFileSync(path.join(__dirname, "schemas", "tenantSchema.postgresql.sql"), "utf8").replace(/\r\n/g, "\n");
const deployYml = fs.readFileSync(path.join(__dirname, "..", ".github", "workflows", "deploy.yml"), "utf8");
const squash = (sql) => sql.replace(/\s+/g, " ").trim();

test("the four tables, with the right keys, constraints and indexes", () => {
    assert.deepEqual(SMART_SHEETS_TABLES, ["smart_sheets", "smart_sheet_access", "smart_sheet_worksheets", "smart_sheet_cells"]);
    const sql = SMART_SHEETS_SCHEMA_STATEMENTS.map(squash).join("\n");

    for (const table of SMART_SHEETS_TABLES) assert.match(sql, new RegExp(`CREATE TABLE "${table}" \\(`));

    // identity keys, status/permission whitelists
    assert.match(sql, /"smart_sheets" \( "id" integer GENERATED BY DEFAULT AS IDENTITY/);
    assert.match(sql, /"status" varchar NOT NULL DEFAULT 'active' CHECK \("status" IN \('active', 'archived'\)\)/);
    assert.match(sql, /"permission" varchar NOT NULL DEFAULT 'edit' CHECK \("permission" IN \('view', 'edit'\)\)/);
    assert.match(sql, /"revision" bigint NOT NULL DEFAULT 0/);
    assert.match(sql, /"deleted_at" timestamp NULL DEFAULT NULL/, "soft delete");

    // one assignment per (sheet, user); unique tab keys per sheet; one row per cell position
    assert.match(sql, /UNIQUE \("sheet_id", "user_id"\)/);
    assert.match(sql, /UNIQUE \("sheet_id", "ws_key"\)/);
    assert.match(sql, /PRIMARY KEY \("worksheet_id", "row_idx", "col_idx"\)/);

    // foreign keys: children vanish with their parent; actors are kept but nulled
    assert.match(sql, /"fk_smart_sheet_access_sheet" FOREIGN KEY \("sheet_id"\) REFERENCES "smart_sheets" \("id"\) ON DELETE CASCADE/);
    assert.match(sql, /"fk_smart_sheet_access_user" FOREIGN KEY \("user_id"\) REFERENCES "users" \("id"\) ON DELETE CASCADE/);
    assert.match(sql, /"fk_smart_sheet_worksheets_sheet" FOREIGN KEY \("sheet_id"\) REFERENCES "smart_sheets" \("id"\) ON DELETE CASCADE/);
    assert.match(sql, /"fk_smart_sheet_cells_worksheet" FOREIGN KEY \("worksheet_id"\) REFERENCES "smart_sheet_worksheets" \("id"\) ON DELETE CASCADE/);
    assert.match(sql, /"fk_smart_sheet_cells_sheet" FOREIGN KEY \("sheet_id"\) REFERENCES "smart_sheets" \("id"\) ON DELETE CASCADE/);
    for (const actor of ["fk_smart_sheets_created_by", "fk_smart_sheets_updated_by", "fk_smart_sheet_access_granted_by", "fk_smart_sheet_cells_updated_by"]) {
        assert.match(sql, new RegExp(`"${actor}" FOREIGN KEY \\("\\w+"\\) REFERENCES "users" \\("id"\\) ON DELETE SET NULL`));
    }

    // every foreign-key column is indexed (or is the leading column of a key)
    for (const index of ["idx_smart_sheets_status_deleted", "idx_smart_sheet_access_user", "idx_smart_sheet_worksheets_sheet_position", "idx_smart_sheet_cells_sheet"]) {
        assert.match(sql, new RegExp(`CREATE INDEX "${index}"`));
    }

    // tables are created before anything references them
    const order = SMART_SHEETS_SCHEMA_STATEMENTS.map((s) => (/CREATE TABLE "(\w+)"/.exec(s) || [])[1]).filter(Boolean);
    assert.deepEqual(order, ["smart_sheets", "smart_sheet_access", "smart_sheet_worksheets", "smart_sheet_cells"]);

    // nothing destructive, no data access, no jsonb "?" operators that the placeholder converter would mangle
    assert.doesNotMatch(sql.replace(/ON DELETE (CASCADE|SET NULL)/g, ""), /\b(DROP|TRUNCATE|DELETE|UPDATE|INSERT|ALTER)\b/i);
    assert.equal((sql.match(/\?/g) || []).length, 0);
    assert.doesNotMatch(sql, /company_id/, "tenant isolation is the tenant database itself");
});

test("every tenant-schema statement is in tenantSchema.postgresql.sql, verbatim", () => {
    for (const statement of SMART_SHEETS_SCHEMA_STATEMENTS) {
        assert.ok(schemaFile.includes(`${statement};`), `schema file is missing:\n${statement.split("\n")[0]}`);
    }
    // ...and nothing else about smart sheets lives there
    const mentions = (schemaFile.match(/CREATE (?:TABLE|INDEX) "(?:idx_)?smart_sheet\w*"/g) || []).length;
    assert.equal(mentions, SMART_SHEETS_SCHEMA_STATEMENTS.length);
});

test("the schema file keeps the plain CREATE TABLE form (tenantProvisioningService reads table names with a regex)", () => {
    assert.doesNotMatch(SMART_SHEETS_SCHEMA_STATEMENTS.join("\n"), /IF NOT EXISTS/);
    // the exact regex tenantProvisioningService uses to list expected tables
    const names = [];
    const re = /CREATE TABLE\s+"?([a-zA-Z0-9_]+)"?/g;
    let match;
    while ((match = re.exec(schemaFile)) !== null) names.push(match[1]);
    for (const table of SMART_SHEETS_TABLES) assert.ok(names.includes(table), table);
    assert.ok(!names.includes("IF"), "an IF NOT EXISTS would be read as a table called IF");

    // the provisioner strips "--" comment lines and splits on ";" -- no statement may contain a stray semicolon
    for (const statement of SMART_SHEETS_SCHEMA_STATEMENTS) assert.equal(statement.includes(";"), false);
});

test("the migration form of every statement is re-runnable", () => {
    assert.equal(SMART_SHEETS_MIGRATION_STATEMENTS.length, SMART_SHEETS_SCHEMA_STATEMENTS.length);
    for (const statement of SMART_SHEETS_MIGRATION_STATEMENTS) {
        assert.match(statement, /^CREATE (TABLE|INDEX) IF NOT EXISTS "/);
    }
    // identical apart from IF NOT EXISTS
    SMART_SHEETS_SCHEMA_STATEMENTS.forEach((statement, i) => {
        assert.equal(SMART_SHEETS_MIGRATION_STATEMENTS[i].replace(" IF NOT EXISTS", ""), statement);
    });
});

// ---- the script's behaviour, against a recording fake pool ----

function fakePool({ existing = [], failOn = null, missingDb = false } = {}) {
    const log = [];
    const connection = {
        async beginTransaction() { log.push("BEGIN"); },
        async commit() { log.push("COMMIT"); },
        async rollback() { log.push("ROLLBACK"); },
        release() { log.push("RELEASE"); },
        async query(sql, params) {
            log.push(squash(sql).slice(0, 60));
            if (failOn && squash(sql).includes(failOn)) throw new Error("boom");
            return [[]];
        },
    };
    return {
        log,
        async query(sql) {
            if (missingDb) { const e = new Error('database "x" does not exist'); e.code = "3D000"; throw e; }
            log.push("PROBE");
            return [existing.map((table_name) => ({ table_name }))];
        },
        async getConnection() { return connection; },
    };
}

const quiet = async (work) => {
    const original = { log: console.log, error: console.error };
    console.log = () => {};
    console.error = () => {};
    try { return await work(); } finally { Object.assign(console, original); }
};

test("a fresh database: one transaction, an advisory lock, every statement, then COMMIT", async () => {
    const pool = fakePool();
    const result = await quiet(() => migration.migrateDatabase("tenant_acme", pool));
    assert.equal(result.action, "migrated");
    assert.deepEqual(result.missing, SMART_SHEETS_TABLES);

    assert.equal(pool.log[0], "PROBE");
    assert.equal(pool.log[1], "BEGIN");
    assert.match(pool.log[2], /pg_advisory_xact_lock/);
    const statements = pool.log.slice(3, 3 + SMART_SHEETS_MIGRATION_STATEMENTS.length);
    assert.equal(statements.length, 8);
    statements.forEach((line) => assert.match(line, /^CREATE (TABLE|INDEX) IF NOT EXISTS/));
    assert.deepEqual(pool.log.slice(-2), ["COMMIT", "RELEASE"]);
});

test("already migrated: reports a skip and still only runs idempotent statements", async () => {
    const pool = fakePool({ existing: SMART_SHEETS_TABLES });
    const result = await quiet(() => migration.migrateDatabase("tenant_acme", pool));
    assert.equal(result.action, "skipped");
    assert.deepEqual(result.missing, []);
    assert.ok(pool.log.every((line) => !/DROP|TRUNCATE|DELETE|UPDATE|INSERT|ALTER/.test(line)));
});

test("a failing statement rolls the whole database back and the error propagates", async () => {
    const pool = fakePool({ failOn: "smart_sheet_cells" });
    await assert.rejects(quiet(() => migration.migrateDatabase("tenant_acme", pool)), /boom/);
    assert.ok(pool.log.includes("ROLLBACK"));
    assert.ok(!pool.log.includes("COMMIT"));
    assert.equal(pool.log[pool.log.length - 1], "RELEASE", "the connection is always released");
});

test("--dry-run reads only: no connection, no transaction, nothing written", async () => {
    const pool = fakePool({ existing: ["smart_sheets"] });
    const result = await quiet(() => migration.migrateDatabase("tenant_acme", pool, { dryRun: true }));
    assert.equal(result.action, "dry-run");
    assert.deepEqual(result.missing, ["smart_sheet_access", "smart_sheet_worksheets", "smart_sheet_cells"]);
    assert.deepEqual(pool.log, ["PROBE"]);
});

test("runTargets: a missing legacy database is skipped; any other failure is counted and does not stop the rest", async () => {
    const good = fakePool();
    const broken = fakePool({ failOn: "smart_sheets" });
    const missing = fakePool({ missingDb: true });
    const targets = [
        { label: "legacy database", getPool: () => missing, skipIfMissing: true },
        { label: "tenant_a", getPool: () => broken },
        { label: "tenant_b", getPool: () => good },
    ];
    const outcome = await quiet(() => migration.runTargets(targets));
    assert.deepEqual(outcome, { failures: 1, skipped: 1 });
    assert.ok(good.log.includes("COMMIT"), "a later tenant is still migrated after an earlier failure");

    // a missing database is only forgivable for the legacy target
    const notLegacy = await quiet(() => migration.runTargets([{ label: "tenant_x", getPool: () => fakePool({ missingDb: true }) }]));
    assert.equal(notLegacy.failures, 1);
});

test("buildTargets covers the legacy database and every registered tenant", () => {
    const pools = { legacy: {}, t1: {}, t2: {} };
    const { targets, notices } = migration.buildTargets({
        legacyPool: pools.legacy,
        legacyDbName: "reinsteins",
        companies: [{ company_slug: "a", tenant_db_name: "tenant_a" }, { company_slug: "b", tenant_db_name: "tenant_b" }],
        getTenantPool: (name) => ({ name }),
    });
    assert.deepEqual(targets.map((t) => t.label), ["legacy database", "a (tenant_a)", "b (tenant_b)"]);
    assert.equal(targets[0].skipIfMissing, true);
    assert.equal(targets[1].getPool().name, "tenant_a");
    assert.deepEqual(notices, []);

    const noLegacy = migration.buildTargets({ legacyPool: pools.legacy, legacyDbName: "  ", companies: [], getTenantPool: () => null });
    assert.deepEqual(noLegacy.targets, []);
    assert.match(noLegacy.notices[0], /DB_NAME is not set/);
});

test("the script is safe to require (it only runs when executed) and never touches data tables", () => {
    const source = fs.readFileSync(path.join(__dirname, "_migrate_add_smart_sheets.js"), "utf8");
    assert.match(source, /if \(require\.main === module\)/);
    assert.match(source, /pg_advisory_xact_lock/);
    assert.match(source, /process\.argv\.includes\("--dry-run"\)/);
    assert.doesNotMatch(source, /\b(DROP|TRUNCATE|DELETE FROM|UPDATE\s+"?\w+"?\s+SET|INSERT INTO)\b/i);
});

test("deploy.yml runs the migration before the client build and the restart", () => {
    const migrate = deployYml.indexOf("node server/_migrate_add_smart_sheets.js");
    assert.ok(migrate > 0, "the migration step is in deploy.yml");
    assert.ok(migrate > deployYml.indexOf("node server/_migrate_add_must_change_password.js"), "after the existing migrations");
    assert.ok(migrate < deployYml.indexOf("npm run build"), "before the client build");
    assert.ok(migrate < deployYml.indexOf("systemctl restart"), "before the restart (the new code queries these tables)");
    assert.equal(deployYml.split("\n").some((line) => /continue-on-error/.test(line)), false, "a failed migration must stop the deploy");
    assert.match(deployYml, /set -e/);
});
