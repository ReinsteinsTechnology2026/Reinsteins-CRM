const pool = require('../config/db');

const schema = `CREATE TABLE IF NOT EXISTS notification_email_outbox (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  notification_id integer NOT NULL UNIQUE,
  user_id integer NOT NULL,
  subject text NOT NULL,
  html text NOT NULL,
  plain_text text NOT NULL,
  status varchar(20) NOT NULL DEFAULT 'pending',
  attempts integer NOT NULL DEFAULT 0,
  next_attempt_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  locked_until timestamp NULL,
  last_error_code varchar(60) NULL,
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  sent_at timestamp NULL
)`;

// The table is created by schemas/tenantSchema.postgresql.sql (new tenants) or
// _migrate_add_notification_email_outbox.js (existing databases). The app never
// runs DDL itself: it only checks, so a missing table is reported accurately.
const present = new WeakSet();
const reported = new WeakSet();

function poolOf(db) {
  return db === pool ? db.__getActivePool() : db;
}

async function isOutboxAvailable(db = pool) {
  const active = poolOf(db);
  if (present.has(active)) return true;
  const [rows] = await active.query(`SELECT to_regclass('notification_email_outbox') AS name`);
  if (rows[0]?.name) {
    present.add(active);
    return true;
  }
  return false;
}

// Logs once per pool that the migration has not been applied.
function reportOutboxMissing(db = pool) {
  const active = poolOf(db);
  if (reported.has(active)) return;
  reported.add(active);
  console.error('[notificationEmail] notification_email_outbox is missing; run ' +
    '_migrate_add_notification_email_outbox.js. Emails are NOT being queued or sent for this database.');
}

// Master switch for queueing AND sending notification emails. Fails closed:
//   NOTIFICATION_EMAIL_ENABLED=true   -> enabled (explicit opt-in, any environment)
//   NOTIFICATION_EMAIL_ENABLED=<other non-empty value, e.g. false> -> disabled
//   unset                             -> enabled ONLY when NODE_ENV is development or test,
//                                        so a server whose NODE_ENV is production, unset or
//                                        anything else sends nothing until someone sets it.
// While disabled no email is queued (so enabling later cannot release a backlog of
// stale messages); the in-app notification is unaffected.
function isEmailDeliveryEnabled(env = process.env) {
  const flag = String(env.NOTIFICATION_EMAIL_ENABLED ?? '').trim().toLowerCase();
  if (flag !== '') return flag === 'true';
  return ['development', 'test'].includes(String(env.NODE_ENV ?? '').trim().toLowerCase());
}

// Same statement as the one in schemas/tenantSchema.postgresql.sql; a test compares both.
const dueIndexSql = `CREATE INDEX IF NOT EXISTS "idx_notification_email_outbox_due"
  ON notification_email_outbox (status, next_attempt_at)`;

// Identity of the database a pool really connects to, asked of the server itself
// (not inferred from host/port text, which can differ for the same database, e.g.
// "localhost" vs "127.0.0.1"). Used to avoid processing one database twice.
const identities = new WeakMap();
async function databaseIdentity(db) {
  if (identities.has(db)) return identities.get(db);
  const [rows] = await db.query(`SELECT current_database() AS db, inet_server_port() AS port,
    pg_postmaster_start_time()::text AS started,
    (SELECT oid::text FROM pg_database WHERE datname = current_database()) AS oid`);
  const r = rows[0];
  const identity = `${r.started}|${r.port}|${r.db}|${r.oid}`;
  identities.set(db, identity);
  return identity;
}

// Every database that can hold an outbox: the legacy database, plus each tenant
// database registered in the platform database. No company is excluded by slug.
// Targets whose verified identity was already seen are dropped (legacy comes
// first). A target that cannot be resolved or reached is returned with `error`
// so the caller can report it without affecting the other targets.
//   activeOnly=true  (worker): only active companies, resolved with getTenantPoolForCompany
//   activeOnly=false (migration): every company that has a tenant database
async function listOutboxTargets({ platformPool, legacyPool, resolveTenantPool, activeOnly = true }) {
  const targets = [];
  const seen = new Map();

  const add = async (label, kind, resolve) => {
    try {
      const db = resolve();
      const identity = await databaseIdentity(db);
      if (seen.has(identity)) {
        targets.push({ label, kind, duplicateOf: seen.get(identity) });
        return;
      }
      seen.set(identity, label);
      targets.push({ label, kind, db, identity });
    } catch (error) {
      targets.push({ label, kind, error });
    }
  };

  await add('legacy', 'legacy', () => legacyPool);

  const [companies] = await platformPool.query(
    `SELECT id, company_slug, status, tenant_db_name FROM companies
     WHERE tenant_db_name IS NOT NULL AND tenant_db_name <> ''
     ${activeOnly ? "AND status = 'active'" : ''} ORDER BY id`
  );
  for (const company of companies) {
    await add(company.company_slug, 'tenant', () => resolveTenantPool(company));
  }
  return targets;
}

